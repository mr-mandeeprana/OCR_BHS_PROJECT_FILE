"""
OCR_BHS - Processing Queue
===========================

Central thread-safe queues for asynchronous OCR and barcode processing.

Architecture:

    Live Pipeline
         |
         +---- OCR Task ------> OCR Queue ------> OCR Workers
         |
         +---- Barcode Task --> Barcode Queue -> Barcode Workers
                                      |
                                      v
                                Result Queue
                                      |
                                      v
                                Result Manager


IMPORTANT:
-----------
The live RTSP / YOLO / ByteTrack pipeline must NEVER wait for
OCR or barcode processing.

Therefore:
    submit_ocr()
    submit_barcode()

use put_nowait().

If a queue is full, the task is dropped instead of blocking
the camera/inference loop.
"""

from __future__ import annotations

import queue
import threading
from dataclasses import dataclass, field
from typing import Any, Optional


# =====================================================================
# OCR TASK
# =====================================================================


@dataclass
class OCRTask:
    """
    Task submitted to the asynchronous OCR pipeline.

    Parameters
    ----------
    task_id:
        Globally unique task identifier.

    camera_id:
        Camera that produced the frame.

    track_id:
        ByteTrack ID for this camera.

    frame:
        Image/frame to process.

    timestamp:
        Timestamp associated with the frame.

    frame_id:
        Frame number from the live camera/inference pipeline.
        Carried through to the result for end-to-end traceability
        (camera frame -> track -> task -> result -> DB row).

    metadata:
        Additional information such as:
            detection confidence
            bbox
            frame number
            camera timestamp
            best-frame score
            physical event information
    """

    task_id: str

    camera_id: str

    track_id: int

    frame: Any

    timestamp: float

    # Frame number from the live camera/inference pipeline.
    frame_id: Optional[int] = None

    metadata: dict[str, Any] = field(
        default_factory=dict
    )


# =====================================================================
# BARCODE TASK
# =====================================================================


