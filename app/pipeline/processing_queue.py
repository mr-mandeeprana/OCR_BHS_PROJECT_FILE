def main() -> None:

    import time

    print()
    print("=" * 70)
    print("OCR_BHS - PROCESSING QUEUE TEST")
    print("=" * 70)

    # --------------------------------------------------------------
    # Create queue
    # --------------------------------------------------------------

    processing_queue = ProcessingQueue(
        max_size=3
    )

    print()
    print("Initial status:")
    print(
        processing_queue.status()
    )

    # --------------------------------------------------------------
    # OCR test
    # --------------------------------------------------------------

    print()
    print("Submitting OCR tasks...")

    for index in range(5):

        task = OCRTask(
            task_id=f"ocr-test-{index}",
            camera_id="camera_1",
            track_id=index + 1,
            frame=None,
            timestamp=time.time(),
            frame_id=index,
            metadata={
                "test": True,
            },
        )

        accepted = (
            processing_queue.submit_ocr(
                task
            )
        )

        print(
            f"OCR task {index}: "
            f"{'ACCEPTED' if accepted else 'DROPPED'}"
        )

    # --------------------------------------------------------------
    # Barcode test
    # --------------------------------------------------------------

    print()
    print("Submitting barcode tasks...")

    for index in range(5):

        task = BarcodeTask(
            task_id=f"barcode-test-{index}",
            camera_id="camera_1",
            track_id=index + 1,
            frame=None,
            timestamp=time.time(),
            frame_id=index,
            metadata={
                "test": True,
            },
        )

        accepted = (
            processing_queue
            .submit_barcode(
                task
            )
        )

        print(
            f"Barcode task {index}: "
            f"{'ACCEPTED' if accepted else 'DROPPED'}"
        )

    # --------------------------------------------------------------
    # Status
    # --------------------------------------------------------------

    print()
    print("Queue status:")

    print(
        processing_queue.status()
    )

    # --------------------------------------------------------------
    # Retrieve OCR task
    # --------------------------------------------------------------

    ocr_task = (
        processing_queue.get_ocr(
            timeout=0.1
        )
    )

    if ocr_task:

        print()
        print(
            "Retrieved OCR task:"
        )

        print(
            f"  task_id  : "
            f"{ocr_task.task_id}"
        )

        processing_queue.ocr_done()

    # --------------------------------------------------------------
    # Retrieve barcode task
    # --------------------------------------------------------------

    barcode_task = (
        processing_queue.get_barcode(
            timeout=0.1
        )
    )

    if barcode_task:

        print()
        print(
            "Retrieved Barcode task:"
        )

        print(
            f"  task_id  : "
            f"{barcode_task.task_id}"
        )

        processing_queue.barcode_done()

    # --------------------------------------------------------------
    # Result test
    # --------------------------------------------------------------

    print()
    print("Submitting result...")

    result = OCRTaskResult(
        task_id="ocr-result-1",
        camera_id="camera_1",
        track_id=1,
        result={
            "text": "TEST-IATA",
        },
        timestamp=time.time(),
        frame_id=0,
        metadata={
            "test": True,
        },
    )

    accepted = (
        processing_queue
        .submit_result(
            result
        )
    )

    print(
        "Result:",
        "ACCEPTED"
        if accepted
        else "DROPPED",
    )

    # --------------------------------------------------------------
    # Retrieve result
    # --------------------------------------------------------------

    received = (
        processing_queue.get_result(
            timeout=0.1
        )
    )

    if received:

        print()
        print(
            "Retrieved result:"
        )

        print(
            f"  task_id  : "
            f"{received.task_id}"
        )

        print(
            f"  camera   : "
            f"{received.camera_id}"
        )

        print(
            f"  track_id : "
            f"{received.track_id}"
        )

        print(
            f"  frame_id : "
            f"{received.frame_id}"
        )

        processing_queue.result_done()

    # --------------------------------------------------------------
    # Final status
    # --------------------------------------------------------------

    print()
    print("Final status:")

    print(
        processing_queue.status()
    )

    # --------------------------------------------------------------
    # Close
    # --------------------------------------------------------------

    processing_queue.close(
        clear_pending=True
    )

    print()
    print(
        "Queue closed."
    )

    print()
    print("=" * 70)
    print("PROCESSING QUEUE TEST COMPLETE")
    print("=" * 70)


if __name__ == "__main__":
    main()